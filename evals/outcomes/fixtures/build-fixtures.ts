#!/usr/bin/env node
/**
 * Regenerate the two fixtures that are ENGINE OUTPUT rather than hand-written:
 *
 *   grid/    the engine E2E's main.tscn as it stands after the A/C waves —
 *            5x5 Grid/Box_* + 9 GridBox_* MeshInstance3Ds, CollidableSphere with
 *            StaticBody3D/CollisionShape3D, LightRig (Key/Fill/Rim), a
 *            WorldEnvironment with a ProceduralSky, Camera3D current at (8,6,8):
 *            50 nodes. The E2E repo commits only the empty bootstrap main.tscn
 *            and builds this state live (tests/1summer_engine/scene_scripting_e2e/
 *            fixtures/grid_script.json + ctx_stdlib.json), so this script replays
 *            those two scripts verbatim and saves the result.
 *   rigged/  rig.tscn: a script-built Skeleton3D ("Rig": root/arm/hand) with a
 *            box mesh and an AnimationPlayer holding `idle` and `walk` clips —
 *            the Wave G shape, built in-script so no GLB import is needed.
 *
 * Usage: SUMMER_EDITOR_BIN=<editor> node evals/outcomes/fixtures/build-fixtures.ts [--render xvfb|headless]
 * Needs `npm run build` (the toolkit's engine client is imported from dist/).
 */

import { cpSync, mkdtempSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { bootEditor, defaultRenderMode, findEditorBinary, runOp } from "../lib/engine.ts";

const here = dirname(fileURLToPath(import.meta.url));

const GRID_SCRIPT = `func run(ctx):
\tvar root = ctx.get_scene_root()
\tif root == null:
\t\tctx.report("error", "no scene root")
\t\treturn null
\tvar grid = Node3D.new()
\tgrid.name = "Grid"
\troot.add_child(grid)
\tvar count = 0
\tfor x in range(5):
\t\tfor z in range(5):
\t\t\tvar mi = MeshInstance3D.new()
\t\t\tmi.name = "Box_%d_%d" % [x, z]
\t\t\tmi.mesh = BoxMesh.new()
\t\t\tmi.position = Vector3(x * 2.0, 0.0, z * 2.0)
\t\t\tgrid.add_child(mi)
\t\t\tcount += 1
\tctx.set_owner_recursive(grid)
\tctx.report("count", count)
\treturn {"built": count}
`;

const CTX_STDLIB_SCRIPT = `func run(ctx):
\tvar mat = ctx.make_material({"albedo": "#4488ff", "roughness": 0.3})
\tvar made = ctx.grid(3, 3, Vector3(2, 0, 2), func(i, _pos):
\t\tvar m = ctx.add_mesh("box", "GridBox_%d" % i)
\t\tctx.apply_material(m, mat)
\t\treturn m
\t)
\tctx.add_mesh_with_collision("sphere", "CollidableSphere", null, {"radius": 0.75})
\tctx.add_light_rig()
\tctx.ensure_environment()
\tctx.add_camera(Vector3(8, 6, 8), Vector3(2, 0, 2), true)
\tvar saved = ctx.save_scene()
\treturn {"made": made.size(), "saved": saved}
`;

const RIG_SCRIPT = `func run(ctx):
\tvar skel = ctx.add_node("Skeleton3D", "Rig")
\tskel.add_bone("root")
\tskel.set_bone_rest(0, Transform3D())
\tskel.add_bone("arm")
\tskel.set_bone_parent(1, 0)
\tskel.set_bone_rest(1, Transform3D(Basis(), Vector3(0, 1, 0)))
\tskel.add_bone("hand")
\tskel.set_bone_parent(2, 1)
\tskel.set_bone_rest(2, Transform3D(Basis(), Vector3(0, 0.5, 0)))
\tctx.add_mesh("box", "RigMesh", skel, {"size": Vector3(0.4, 1.6, 0.4), "position": Vector3(0, 0.8, 0)})
\tvar p = ctx.animate(skel, "Rig:arm/rotation", [[0.0, Vector3.ZERO], [0.5, Vector3(0, 0, 0.1)], [1.0, Vector3.ZERO]], "idle", true)
\tctx.animate(skel, "Rig:arm/rotation", [[0.0, Vector3(0.6, 0, 0)], [0.4, Vector3(-0.6, 0, 0)], [0.8, Vector3(0.6, 0, 0)]], "walk", true, p)
\tctx.animate(skel, "Rig:hand/rotation", [[0.0, Vector3(0.3, 0, 0)], [0.4, Vector3(-0.3, 0, 0)], [0.8, Vector3(0.3, 0, 0)]], "walk", true, p)
\tctx.add_camera(Vector3(3, 2, 4), Vector3(0, 1, 0), true)
\tvar saved = ctx.save_scene()
\treturn {"clips": p.get_animation_list(), "saved": saved}
`;

const PROJECT_GODOT = (name: string, mainScene: string, extra = "") => `; Outcome-eval fixture \`${name}\`: generated by evals/outcomes/fixtures/build-fixtures.ts
; against the engine build named in evals/outcomes/engine.lock — regenerate, do
; not hand-edit. The runner copies this directory to a throwaway project before
; it boots the editor. No .godot/ cache is committed. The [audio]/[rendering]
; pins keep the game child free of Vulkan/ALSA probing noise under Xvfb.

config_version=5

[application]

config/name="Outcome Eval ${name}"
run/main_scene="${mainScene}"
config/features=PackedStringArray("4.7")

[audio]

driver/driver="Dummy"
${extra}
[rendering]

renderer/rendering_method="gl_compatibility"
renderer/rendering_method.mobile="gl_compatibility"
`;

async function buildOne(
  binary: string,
  render: ReturnType<typeof defaultRenderMode>,
  name: string,
  scene: string,
  bootstrapRoot: string,
  scripts: string[],
  extraProjectSection = ""
): Promise<void> {
  const work = mkdtempSync(join(tmpdir(), `outcome-fixture-${name}-`));
  const project = join(work, "project");
  mkdirSync(project);
  writeFileSync(join(project, "project.godot"), PROJECT_GODOT(name, scene, extraProjectSection));
  const sceneFile = scene.replace("res://", "");
  writeFileSync(join(project, sceneFile), `[gd_scene format=3]\n\n[node name="Main" type="${bootstrapRoot}"]\n`);
  const editor = await bootEditor({ binary, projectDir: project, render, logPath: join(work, "editor.log") });
  try {
    const opened = await runOp(editor.client, { op: "OpenScene", path: scene });
    if (!opened.ok) throw new Error(`OpenScene failed: ${JSON.stringify(opened.result)}`);
    for (const source of scripts) {
      const ran = await runOp(editor.client, { op: "RunSceneScript", script_source: source, max_seconds: 30 }, 90_000);
      if (!ran.ok) throw new Error(`RunSceneScript failed: ${JSON.stringify(ran.result).slice(0, 1200)}`);
      console.log(`[${name}] script ok:`, JSON.stringify(ran.result.result));
    }
    const saved = await runOp(editor.client, { op: "SaveScene" });
    if (!saved.ok) throw new Error(`SaveScene failed: ${JSON.stringify(saved.result)}`);
    const snap = await runOp(editor.client, { op: "GetWorldSnapshot", include_2d: true });
    console.log(`[${name}] total_nodes:`, snap.result.total_nodes, "counts:", JSON.stringify(snap.result.counts));
  } finally {
    await editor.stop();
  }
  const out = join(here, name);
  rmSync(out, { recursive: true, force: true });
  mkdirSync(out, { recursive: true });
  cpSync(join(project, "project.godot"), join(out, "project.godot"));
  cpSync(join(project, sceneFile), join(out, sceneFile));
  console.log(`[${name}] wrote ${out} (${readFileSync(join(out, sceneFile), "utf8").length} bytes of ${sceneFile})`);
  rmSync(work, { recursive: true, force: true });
}

async function main(): Promise<number> {
  const args = process.argv.slice(2);
  const renderIdx = args.indexOf("--render");
  const render = defaultRenderMode(renderIdx === -1 ? undefined : args[renderIdx + 1]);
  const binary = findEditorBinary();
  if (!binary) {
    console.error("build-fixtures: set SUMMER_EDITOR_BIN to the editor binary");
    return 2;
  }
  await buildOne(binary, render, "grid", "res://main.tscn", "Node3D", [GRID_SCRIPT, CTX_STDLIB_SCRIPT]);
  await buildOne(binary, render, "rigged", "res://rig.tscn", "Node3D", [RIG_SCRIPT]);
  return 0;
}

process.exit(await main());
